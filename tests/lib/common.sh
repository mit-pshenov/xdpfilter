# ── §5.61 (MVP-4.21 / B30) operator-id → internal-slot remap ─────────────
# Post-B30 the raw `rule_counters` / `rules_inner` BPF maps are SLOT-keyed
# (slot = a rule's rank in ascending-unique-id order), decoupled from the
# operator `id`. A test that peeks those maps BY OPERATOR ID must first
# resolve id->slot through the `slot_rule_id` pin's active/selected half —
# exactly as the production exporter does (design.md §5.61 EDIT-1 /
# D-mvp-4.21-RAWMAP-REMAP). These helpers centralise that remap.
#
# active_idx_of <iface> → echoes the shared active_idx value (0|1) or empty.
active_idx_of() {
    local iface="$1"
    local raw v hex
    raw=$(sudo -n bpftool map dump pinned "${PIN_ROOT}/${iface}/active_idx" --json 2>/dev/null)
    [[ -z "${raw}" ]] && return
    v=$(printf '%s' "${raw}" | jq -r '.[0].formatted.value // empty' 2>/dev/null)
    if [[ -n "${v}" && "${v}" != "null" ]]; then echo "${v}"; return; fi
    hex=$(printf '%s' "${raw}" | jq -r '.[0].value[0] // empty' 2>/dev/null | sed 's/^0x//')
    if [[ -n "${hex}" && "${hex}" != "null" ]]; then printf '%d\n' "0x${hex}"; fi
}

# half_of_pin <pin> → echoes 0 for a *_a pin, 1 for a *_b pin (the shared
# active_idx governs ALL parallel-outer maps uniformly, so the _a/_b suffix
# of ANY parallel pin names its ruleset half). Empty if neither suffix.
half_of_pin() {
    case "$1" in
        *_a) echo 0 ;;
        *_b) echo 1 ;;
        *)   return 1 ;;
    esac
}

# id_to_slot <iface> <id> [half] → echoes the slot holding operator <id> in
# ruleset half <half> (default = active half), or EMPTY if that id is not
# loaded in that half. Reads the slot_rule_id pin (delegates to id_to_slot.py).
id_to_slot() {
    local iface="$1" id="$2" half="${3:-}"
    if [[ -z "${half}" ]]; then half=$(active_idx_of "${iface}"); fi
    [[ -z "${half}" ]] && return
    sudo -n python3 "${TEST_DIR}/lib/id_to_slot.py" \
        "${PIN_ROOT}/${iface}/slot_rule_id" "${half}" "${id}" 2>/dev/null
}

# read_rule_counter_by_id <iface> <counter_inner_pin> <id>
#   Resolves <id> -> slot (half inferred from the inner pin's _a/_b suffix,
#   falling back to the active half) and reads that slot's counter. Echoes 0
#   if the id is not present in that half (an unloaded rule has no counter).
read_rule_counter_by_id() {
    local iface="$1" pin="$2" id="$3" half slot
    half=$(half_of_pin "${pin}") || half=$(active_idx_of "${iface}")
    slot=$(id_to_slot "${iface}" "${id}" "${half}")
    [[ -z "${slot}" ]] && { echo 0; return; }
    sudo -n python3 "${TEST_DIR}/lib/read_rule_counters.py" "${pin}" "${slot}"
}

# ── Frame injection (scapy / raw AF_PACKET) ──────────────────────────────
# Per §5.25 P1: python3 is spawned via `ip netns exec` so the
# AF_PACKET socket opened inside the interpreter binds inside the netns
# where the iface lives (setns(2) happens before exec; child inherits).
# inject_eth <iface> <src_mac> <dst_mac>
inject_eth() {
    local iface="$1" src="$2" dst="$3"
    ${NSEXEC} python3 "${TEST_DIR}/inject/inject_eth.py" "${iface}" "${src}" "${dst}"
}

# inject_runt <iface> — sub-14-byte frame for malformed-frame test.
inject_runt() {
    local iface="$1"
    ${NSEXEC} python3 "${TEST_DIR}/inject/inject_runt.py" "${iface}"
}

# ── XDP-on-iface query ────────────────────────────────────────────────────
# Echoes the attached XDP prog id, or empty string if none.
# Per §5.25 P1: iface lives inside ${NETNS}, so `ip link show` must run
# there too.
xdp_prog_id() {
    local iface="$1"
    ${NSEXEC} ip -j link show "${iface}" 2>/dev/null | jq -r '
        .[0]
        | (.xdp.prog.id // .xdp.attached[]?.prog.id // empty)
    ' | head -n1
}

# ── BPF prog count snapshot (kept for legacy use) ────────────────────────
# Per §5.21 C4, the §6.6 baseline/final clause is dropped — this helper
# is no longer the §6.6 ownership signal (per-iface xdp_prog_id is).
# Retained for any out-of-tree or diagnostic use.
prog_count() {
    sudo -n bpftool prog show --json 2>/dev/null | jq 'length'
}

# ── §5.26 MVP-3.1 helpers ────────────────────────────────────────────────
# apply_config <path-to-yaml> <iface> [extra-args...]
#   Thin wrapper that invokes the loader's `apply` subcommand inside the
#   per-PID netns. Same NSEXEC discipline as inject_eth / xdp_prog_id —
#   the iface lives in ${NETNS} so we must enter the netns to address it.
#   Returns the loader's exit code untouched (so tests can assert rc==9
#   on ConfigError, rc==0 on success, etc.).
apply_config() {
    local config_path="$1" iface="$2"
    shift 2
    ${NSEXEC} "$(find_loader)" apply -f "${config_path}" --iface "${iface}" "$@"
}

# wait_for_active_idx_flip <iface> <expected> [timeout_ms=2000] [poll_ms=20]
#   Polls bpftool's dump of the per-iface active_idx pin until the slot-0
#   value matches `expected`. Returns 0 on match, 1 on timeout.
#   Used by §6.23 / §6.24 / §6.25 to observe the atomic swap commit.
wait_for_active_idx_flip() {
    local iface="$1" expected="$2"
    local timeout_ms="${3:-2000}" poll_ms="${4:-20}"
    local pin="${PIN_ROOT}/${iface}/active_idx"
    local waited_ms=0 cur
    while (( waited_ms < timeout_ms )); do
        cur=$(sudo -n bpftool map dump pinned "${pin}" -j 2>/dev/null \
              | jq -r '.[0].formatted.value // .[0].value[0] // .[0].value' 2>/dev/null || true)
        if [[ "${cur}" == "${expected}" ]]; then
            return 0
        fi
        sleep "$(awk -v ms="${poll_ms}" 'BEGIN{printf "%.3f", ms/1000.0}')"
        waited_ms=$(( waited_ms + poll_ms ))
    done
    return 1
}

# kill_loader_keep_link <iface>
#   Sends SIGKILL to any lingering xdpfilter process AFTER the apply has
#   pinned the link. P0a's contract is the link survives loader-process
#   termination — this helper makes the test explicit. In practice the
#   `apply` invocation has already exited by the time the test reaches the
#   step, so this is belt-and-suspenders (per §6.25 step 10). ENOENT-safe.
kill_loader_keep_link() {
    local iface="$1"
    sudo -n pkill -9 -f "xdpfilter.*${iface}" 2>/dev/null || true
}
